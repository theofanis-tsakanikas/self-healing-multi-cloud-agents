"""Replay-mode eval: score the failure corpus against the REAL deterministic Medic logic.

Produces `evals/report/metrics.json` + `evals/report/REPORT.md` (committed, CI `--check`ed).
This is the offline regression net for the Medic's routing + evidence gate — the heart of
the self-heal loop, runnable by anyone with no cloud, no credentials, no LLM key.
"""

from __future__ import annotations

import argparse
import json
import sys
from collections import defaultdict
from pathlib import Path

_REPO_ROOT = Path(__file__).resolve().parents[2]
if str(_REPO_ROOT) not in sys.path:
    sys.path.insert(0, str(_REPO_ROOT))

from evals.harness.deterministic import (  # noqa: E402
    evidence_gate_accepts,
    evidence_markers,
    load_corpus,
    resolve_owner,
)

METRICS_JSON = _REPO_ROOT / "evals" / "report" / "metrics.json"
REPORT_MD = _REPO_ROOT / "evals" / "report" / "REPORT.md"


def _pct(correct: int, total: int) -> float:
    return round(100.0 * correct / total, 1) if total else 100.0


def evaluate(cases: list[dict]) -> dict:
    """Score every case's routing + evidence-gate expectation against the real functions."""
    routing_total = routing_correct = 0
    gate_total = gate_correct = 0
    routing_failures: list[dict] = []
    gate_failures: list[dict] = []
    per_class: dict[str, dict] = defaultdict(
        lambda: {"routing_total": 0, "routing_correct": 0, "gate_total": 0, "gate_correct": 0}
    )

    for c in cases:
        fc = c["failure_class"]

        if c.get("expected_owner") is not None:
            routing_total += 1
            per_class[fc]["routing_total"] += 1
            actual = resolve_owner(c["trigger_log"])
            if actual == c["expected_owner"]:
                routing_correct += 1
                per_class[fc]["routing_correct"] += 1
            else:
                routing_failures.append({"id": c["id"], "expected": c["expected_owner"], "actual": actual})

        if c.get("evidence_gate"):
            gate_total += 1
            per_class[fc]["gate_total"] += 1
            accepts = evidence_gate_accepts(c["trigger_log"])
            expected_pass = c["evidence_gate"] == "pass"
            if accepts == expected_pass:
                gate_correct += 1
                per_class[fc]["gate_correct"] += 1
            else:
                gate_failures.append({"id": c["id"], "expected": c["evidence_gate"], "accepted": accepts})

    return {
        "corpus_cases": len(cases),
        "routing": {
            "total": routing_total,
            "correct": routing_correct,
            "accuracy_pct": _pct(routing_correct, routing_total),
            "failures": routing_failures,
        },
        "evidence_gate": {
            "total": gate_total,
            "correct": gate_correct,
            "accuracy_pct": _pct(gate_correct, gate_total),
            "failures": gate_failures,
        },
        "by_failure_class": {k: per_class[k] for k in sorted(per_class)},
        "evidence_markers": list(evidence_markers()),
        "all_passed": not routing_failures and not gate_failures,
    }


def render_report(m: dict) -> str:
    r, g = m["routing"], m["evidence_gate"]
    out: list[str] = []
    out.append("# Medic self-heal — offline eval report")
    out.append("")
    out.append(
        "> Generated by `python -m evals.harness.runner` from `evals/corpus/corpus.json`. "
        "Scores the **real** deterministic Medic routing + evidence gate (no cloud, no LLM, no "
        "credentials) — the offline regression net for the self-heal loop. Run it yourself: "
        "`make eval-replay`."
    )
    out.append("")
    status = "✅ all deterministic checks pass" if m["all_passed"] else "❌ regressions detected"
    out.append(
        f"**{status}** — routing {r['correct']}/{r['total']} ({r['accuracy_pct']}%), "
        f"evidence gate {g['correct']}/{g['total']} ({g['accuracy_pct']}%), "
        f"{m['corpus_cases']} corpus cases."
    )
    out.append("")
    out.append("## What this measures")
    out.append("")
    out.append(
        "- **Routing** — for each real CI-failure log, does the Medic's deterministic router "
        "(`_ci_error_owner` + the failing-file fallback) hand it to the right agent "
        "(architect for script logic, infra for missing library/secret/resource)?"
    )
    out.append(
        "- **Evidence gate** — does `request_fix` accept genuine failure text and refuse "
        "marker-less speculation / clean / green output (anti-hallucination)?"
    )
    out.append("")
    out.append("## By failure class")
    out.append("")
    out.append("| Failure class | Routing | Evidence gate |")
    out.append("| --- | --- | --- |")
    for fc, v in m["by_failure_class"].items():
        rt = f"{v['routing_correct']}/{v['routing_total']}" if v["routing_total"] else "—"
        gt = f"{v['gate_correct']}/{v['gate_total']}" if v["gate_total"] else "—"
        out.append(f"| `{fc}` | {rt} | {gt} |")
    out.append("")
    if not m["all_passed"]:
        out.append("## Regressions")
        out.append("")
        for f in r["failures"]:
            out.append(f"- routing `{f['id']}`: expected `{f['expected']}`, got `{f['actual']}`")
        for f in g["failures"]:
            out.append(f"- evidence gate `{f['id']}`: expected `{f['expected']}`, accepted={f['accepted']}")
        out.append("")
    return "\n".join(out) + "\n"


def _default_repo_root() -> Path:
    return _REPO_ROOT


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Offline Medic eval (replay mode) — score the failure corpus.")
    parser.add_argument("--check", action="store_true", help="fail if the committed report/metrics are stale")
    parser.add_argument("--stdout", action="store_true", help="print the report, write nothing")
    parser.add_argument("--json", action="store_true", help="print metrics JSON, write nothing")
    parser.add_argument("--gate", action="store_true", help="exit 1 if any deterministic check regressed")
    args = parser.parse_args(argv)

    cases = load_corpus()
    metrics = evaluate(cases)
    report = render_report(metrics)
    payload = json.dumps(metrics, indent=2) + "\n"

    if args.json:
        print(payload, end="")
    elif args.stdout:
        print(report, end="")

    if args.gate and not metrics["all_passed"]:
        print("EVAL FAIL: deterministic Medic routing/evidence regressed vs the corpus.", file=sys.stderr)
        return 1

    if args.check:
        stale = []
        if not METRICS_JSON.is_file() or METRICS_JSON.read_text(encoding="utf-8") != payload:
            stale.append("evals/report/metrics.json")
        if not REPORT_MD.is_file() or REPORT_MD.read_text(encoding="utf-8") != report:
            stale.append("evals/report/REPORT.md")
        if stale:
            print("STALE eval report (run `make eval-replay`): " + ", ".join(stale), file=sys.stderr)
            return 1
        print("eval report is up to date.")
        return 0

    if not (args.stdout or args.json):
        METRICS_JSON.parent.mkdir(parents=True, exist_ok=True)
        METRICS_JSON.write_text(payload, encoding="utf-8")
        REPORT_MD.write_text(report, encoding="utf-8")
        print(f"wrote {METRICS_JSON.relative_to(_REPO_ROOT)} + {REPORT_MD.relative_to(_REPO_ROOT)}")
        print(f"routing {metrics['routing']['accuracy_pct']}%, evidence gate {metrics['evidence_gate']['accuracy_pct']}%")

    return 0


if __name__ == "__main__":
    sys.exit(main())
