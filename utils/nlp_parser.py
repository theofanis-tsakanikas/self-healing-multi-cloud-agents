# Fields with fixed options → show numbered menu
FIELD_OPTIONS = {
    "target_cloud":   ["aws", "azure", "gcp"],
    "source_db_type": ["postgres", "mysql", "sqlite"],
    "data_domain":    ["sales", "crm", "marketing", "finance", "hr", "logistics", "other"],
    "frequency":      ["daily", "hourly", "realtime", "weekly"],
}

# Fields that are free text → ask open question
FIELD_QUESTIONS = {
    "source_table":  "What is the source table name?",
    "pipeline_slug": "Give a short name for this pipeline (e.g. eu_sales):",
    "owner_team":    "What is the owner team name?",
}

MAX_ROUNDS = 3

# ---------------------------------------------------------------------------
# Private clarification helpers
# ---------------------------------------------------------------------------

def _ask_field(field: str, value) -> str:
    """Interactively ask the user for a single field value."""
    if field in FIELD_OPTIONS:
        options = FIELD_OPTIONS[field]
        while True:
            print(f"\n  ❓ Choose {field}:")
            for i, opt in enumerate(options, 1):
                print(f"     {i}. {opt}")
            raw = input("  ➤ Enter number: ").strip()
            if raw.isdigit() and 1 <= int(raw) <= len(options):
                return options[int(raw) - 1]
            print(f"  ⚠️  Invalid choice — enter a number between 1 and {len(options)}.")

    if field in FIELD_QUESTIONS:
        question = FIELD_QUESTIONS[field]
        while True:
            raw = input(f"\n  ❓ {question}\n  ➤ ").strip()
            if raw:
                return raw
            print("  ⚠️  Value cannot be empty — please try again.")

    # Fallback for any other field
    while True:
        raw = input(f"\n  ❓ Enter value for '{field}':\n  ➤ ").strip()
        if raw:
            return raw
        print("  ⚠️  Value cannot be empty — please try again.")


def _validate_intent(raw: dict) -> tuple:
    """
    Attempt to construct a PipelineIntent from raw dict.
    Returns (PipelineIntent, []) on success or (None, [failed_field_names]) on failure.
    """
    try:
        intent = PipelineIntent(**raw)
        return intent, []
    except ValidationError as exc:
        failed = [e["loc"][0] for e in exc.errors() if e["loc"]]
        # Also catch missing required fields that weren't in raw at all
        required = {"pipeline_slug", "data_domain", "source_db_type", "source_table", "target_cloud"}
        missing = [f for f in required if f not in raw or raw[f] in (None, "", [])]
        all_failed = list(dict.fromkeys(failed + missing))  # deduplicate, preserve order
        return None, all_failed


def _clarification_loop(raw_intent: dict) -> PipelineIntent:
    """
    Interactively collect missing/invalid fields, up to MAX_ROUNDS attempts.
    Raises ValueError after MAX_ROUNDS failed rounds.
    """
    for round_num in range(1, MAX_ROUNDS + 1):
        intent, failed_fields = _validate_intent(raw_intent)
        if intent is not None:
            return intent

        print(f"\n  ⚠️  Missing or invalid fields (round {round_num}/{MAX_ROUNDS}): "
              f"{', '.join(failed_fields)}")
        for field in failed_fields:
            raw_intent[field] = _ask_field(field, raw_intent.get(field))

    # Final validation attempt after last round of corrections
    intent, failed_fields = _validate_intent(raw_intent)
    if intent is not None:
        return intent

    raise ValueError(
        f"❌ Could not collect valid pipeline configuration after {MAX_ROUNDS} rounds. "
        f"Still missing: {', '.join(failed_fields)}"
    )


def _handle_business_rules(raw_rules: list, domain: str) -> list:
    """
    Interactively review, edit, add, or remove business rules extracted by GPT.

    Case A — GPT returned rules: display them and enter the edit/add/remove loop.
    Case B — GPT returned no rules: offer domain suggestions, file import, or skip.

    Args:
        raw_rules: List of rule dicts extracted by _extract_intent (may be empty).
        domain:    The pipeline data domain (e.g. "sales") used for AI suggestions.

    Returns:
        Final list of rule dicts, each containing:
        rule_id, target_column, condition, action, reason.
    """

    _ACTIONS = ["DROP_RECORD", "EXCLUDE_AND_LOG", "FLAG_AS_SUSPICIOUS", "DEFAULT_VALUE"]

    def _print_rules(rules: list) -> None:
        """Print rules with 1-based numbering in a readable block format."""
        for i, r in enumerate(rules, 1):
            print(f"\n  Rule {i}: {r['rule_id']}")
            print(f"    Column    : {r['target_column']}")
            print(f"    Condition : {r['condition']}")
            print(f"    Action    : {r['action']}")
            print(f"    Reason    : {r.get('reason', '')}")

    def _ask_action() -> str:
        """Prompt user to choose an action from a numbered menu."""
        while True:
            print("\n  ❓ Choose action:")
            for i, a in enumerate(_ACTIONS, 1):
                print(f"     {i}. {a}")
            raw = input("  ➤ Enter number: ").strip()
            if raw.isdigit() and 1 <= int(raw) <= len(_ACTIONS):
                return _ACTIONS[int(raw) - 1]
            print(f"  ⚠️  Invalid choice — enter 1–{len(_ACTIONS)}.")

    def _build_rule_form(existing: dict | None = None) -> dict:
        """Guided form to create a new rule or edit an existing one."""
        existing = existing or {}
        rule_id = (
            input(f"\n  ❓ Rule ID [{existing.get('rule_id', '')}]: ").strip()
            or existing.get("rule_id", "")
        )
        col = (
            input(f"  ❓ Target column [{existing.get('target_column', '')}]: ").strip()
            or existing.get("target_column", "")
        )
        print("  ❓ Condition (pandas expression)")
        print("     Examples: df['col'].notna()  |  df['col'] > 0  |  df['col'].str.len() > 3")
        cond = (
            input(f"  [{existing.get('condition', '')}]: ").strip()
            or existing.get("condition", "")
        )
        if existing.get("action"):
            print(f"  ❓ Action — current: {existing['action']}")
        action = _ask_action()
        reason = (
            input(f"  ❓ Reason [{existing.get('reason', '')}]: ").strip()
            or existing.get("reason", "")
        )
        return {
            "rule_id": rule_id,
            "target_column": col,
            "condition": cond,
            "action": action,
            "reason": reason,
        }

    def _parse_rules_via_openai(content: str, system_msg: str) -> list:
        """Send content to OpenAI and parse the returned JSON rules array."""
        resp = client.chat.completions.create(
            model=NL_MODEL,
            temperature=0,
            messages=[
                {"role": "system", "content": system_msg},
                {"role": "user", "content": content},
            ],
        )
        raw = resp.choices[0].message.content.strip()
        raw = re.sub(r"^```(?:json)?\s*", "", raw)
        raw = re.sub(r"\s*```$", "", raw)
        return json.loads(raw)

    def _edit_loop(rules: list) -> list:
        """Main Keep-all / Edit / Add / Remove / Done menu loop."""
        while True:
            _print_rules(rules)
            print("\n  ━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━")
            print("  [1] Keep all")
            print("  [2] Edit a rule")
            print("  [3] Add a rule")
            print("  [4] Remove a rule")
            print("  [5] Done")
            choice = input("  ➤ ").strip()

            if choice in ("1", "5"):
                return rules

            if choice == "2":
                if not rules:
                    print("  ⚠️  No rules to edit.")
                    continue
                idx = input(f"  ❓ Edit rule number (1–{len(rules)}): ").strip()
                if idx.isdigit() and 1 <= int(idx) <= len(rules):
                    rules[int(idx) - 1] = _build_rule_form(rules[int(idx) - 1])
                else:
                    print("  ⚠️  Invalid number.")

            elif choice == "3":
                rules.append(_build_rule_form())

            elif choice == "4":
                if not rules:
                    print("  ⚠️  No rules to remove.")
                    continue
                idx = input(f"  ❓ Remove rule number (1–{len(rules)}): ").strip()
                if idx.isdigit() and 1 <= int(idx) <= len(rules):
                    removed = rules.pop(int(idx) - 1)
                    print(f"  ✅ Removed: {removed['rule_id']}")
                else:
                    print("  ⚠️  Invalid number.")

            else:
                print("  ⚠️  Invalid choice — enter 1–5.")

    # ── Case A: GPT found rules ──────────────────────────────────────────────
    if raw_rules:
        print(f"\n  🚀 {len(raw_rules)} business rule(s) extracted from your description:")
        return _edit_loop(list(raw_rules))

    # ── Case B: No rules found ───────────────────────────────────────────────
    print("\n  ⚠️  No business rules detected in your description.")
    while True:
        print("\n  [1] Suggest rules based on my domain")
        print("  [2] Load rules from a file (.md / .yaml / .json)")
        print("  [3] Continue without rules")
        choice = input("  ➤ ").strip()

        if choice == "1":
            print(f"  🚀 Requesting domain-aware rule suggestions for '{domain}'...")
            suggestions = _parse_rules_via_openai(
                content=f"Domain: {domain}",
                system_msg=(
                    f"You are a data quality expert. Suggest 3-5 business rules for a "
                    f"{domain} data pipeline. Return a JSON array only, no markdown, "
                    f"no explanation. Each item: rule_id, target_column, condition "
                    f"(pandas expression), action (one of DROP_RECORD / "
                    f"EXCLUDE_AND_LOG / FLAG_AS_SUSPICIOUS / DEFAULT_VALUE), reason."
                ),
            )
            print(f"\n  ✅ {len(suggestions)} suggestion(s) received:")
            _print_rules(suggestions)
            sel = input(
                "\n  ❓ Enter rule numbers to keep (e.g. 1,3) or 'all': "
            ).strip().lower()
            if sel == "all":
                selected = list(suggestions)
            else:
                indices = [
                    int(x.strip()) - 1
                    for x in sel.split(",")
                    if x.strip().isdigit()
                ]
                selected = [suggestions[i] for i in indices if 0 <= i < len(suggestions)]
            return _edit_loop(selected)

        if choice == "2":
            path = input("  ❓ Enter file path (.md / .yaml / .json): ").strip()
            try:
                content = open(path, encoding="utf-8").read()
            except OSError as exc:
                print(f"  ⚠️  Cannot read file: {exc}")
                continue
            print("  🚀 Parsing rules from file...")
            loaded = _parse_rules_via_openai(
                content=content,
                system_msg=(
                    "Extract business rules from this content. Return a JSON array "
                    "only, no markdown. Each item: rule_id, target_column, condition "
                    "(pandas expression), action (one of DROP_RECORD / "
                    "EXCLUDE_AND_LOG / FLAG_AS_SUSPICIOUS / DEFAULT_VALUE), reason."
                ),
            )
            print(f"\n  ✅ {len(loaded)} rule(s) parsed from file:")
            return _edit_loop(loaded)

        if choice == "3":
            return []

        print("  ⚠️  Invalid choice — enter 1, 2, or 3.")


def _confirm_and_edit(
    intent: PipelineIntent,
    business_rules: list,
) -> tuple:
    """
    Display a full pipeline configuration summary and ask for confirmation.

    Supports:
      - "yes"              → return (intent, business_rules)
      - "no"               → raise SystemExit
      - "edit <field>"     → re-prompt that field inline, then re-show summary
      - "edit business_rules" → re-run _handle_business_rules, then re-show summary

    Args:
        intent:         Validated PipelineIntent instance.
        business_rules: Current list of rule dicts (may be empty).

    Returns:
        Tuple of (PipelineIntent, list[dict]) after confirmation.
    """
    while True:
        rules_count = len(business_rules)

        print("\n  ━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━")
        print("  Pipeline Configuration Summary")
        print("  ━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━")
        print(f"  Name      : {intent.pipeline_slug:<30} [edit]")
        print(f"  Domain    : {intent.data_domain:<30} [edit]")
        db_cell = f"{intent.source_db_type}  →  table: {intent.source_table}"
        print(f"  Database  : {db_cell:<38} [edit]")
        print(f"  Cloud     : {intent.target_cloud:<30} [edit]")
        print(f"  Frequency : {intent.frequency:<30} [edit]")
        print(f"  Owner     : {intent.owner_team:<30} [edit]")
        if business_rules:
            print(f"  Business Rules ({rules_count}):                        [edit]")
            for i, r in enumerate(business_rules, 1):
                print(f"  {i}. {r['rule_id']}")
                print(f"     column: {r['target_column']}  |  {r['action']}")
        else:
            print(f"  Business Rules : {'none':<32} [edit]")
        print("  ━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━")

        answer = input("  Confirm? [yes / no / edit <field>]: ").strip().lower()

        if answer == "yes":
            print("  ✅ Configuration confirmed.")
            return intent, business_rules

        if answer == "no":
            raise SystemExit("  Pipeline creation cancelled.")

        if answer.startswith("edit "):
            field = answer[5:].strip()

            if field == "business_rules":
                business_rules = _handle_business_rules(business_rules, intent.data_domain)
                continue

            editable = set(FIELD_OPTIONS) | set(FIELD_QUESTIONS)
            if field not in editable:
                all_editable = sorted(editable | {"business_rules"})
                print(f"  ⚠️  Unknown field '{field}'. Editable fields: {', '.join(all_editable)}")
                continue
            new_value = _ask_field(field, getattr(intent, field, None))
            intent = intent.model_copy(update={field: new_value})
            continue

        print("  ⚠️  Invalid response. Type 'yes', 'no', or 'edit <field>'.")


