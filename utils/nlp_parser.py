class PipelineIntent(BaseModel):
    pipeline_slug: str
    data_domain: Literal["sales", "crm", "marketing", "finance", "hr", "logistics", "other"]
    source_db_type: Literal["postgres", "mysql", "sqlite"]
    source_table: str
    target_cloud: Literal["aws", "azure", "gcp"]
    frequency: Literal["daily", "hourly", "realtime", "weekly"] = "daily"
    owner_team: str = "analytics_team"
    business_rules: list = []

    @field_validator("pipeline_slug", "source_table")
    @classmethod
    def must_be_non_empty(cls, v: str) -> str:
        if not v or not v.strip():
            raise ValueError("must be non-empty")
        return v.strip()


