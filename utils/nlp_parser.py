def _load_bootstrap_outputs() -> dict:
    """
    Load real infrastructure values from .bootstrap_outputs.json.
    Returns empty dict if the file does not exist (graceful degradation).
    """
    if _BOOTSTRAP_OUTPUTS_FILE.exists():
        with open(_BOOTSTRAP_OUTPUTS_FILE) as f:
            data = json.load(f)
        print(f"✅ Bootstrap outputs loaded from {_BOOTSTRAP_OUTPUTS_FILE.name}")
        return data
    print(
        f"⚠️  {_BOOTSTRAP_OUTPUTS_FILE.name} not found — using defaults.\n"
        "   Run `python scripts/export_bootstrap_outputs.py` after bootstrap to unlock real values."
    )
    return {}

