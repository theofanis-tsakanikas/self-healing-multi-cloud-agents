def _build_from_answers(
    answers: dict,
    rules: list,
    description: str = "",
    cloud_override: str | None = None,
) -> tuple[dict, dict, dict, dict, str, str]:
    """
    Build the pipeline config 6-tuple from pre-validated UI answers.

    Bypasses the interactive clarification loop; suitable for Streamlit
    where field collection is done via session_state / wizard steps.

    Args:
        answers:        Dict with keys: pipeline_slug, data_domain,
                        source_db_type, source_table, target_cloud,
                        frequency, owner_team.
        rules:          Final list of rule dicts (rule_id, target_column,
                        condition, action, reason).
        description:    Original NL description (embedded in the task string
                        and used for location-based region inference).
        cloud_override: Force a specific cloud (overrides answers["target_cloud"]).

    Returns:
        pipeline_conf, db_conf, rules_conf, infra_conf, pipeline_id, task
    """
    intent = PipelineIntent(**answers)

    slug = _slugify(intent.pipeline_slug)
    cloud = cloud_override if cloud_override in ("aws", "azure", "gcp") else intent.target_cloud
    db_type = intent.source_db_type
    domain = intent.data_domain
    frequency = intent.frequency

    storage_suffix = {"aws": "s3", "azure": "azure", "gcp": "gcp"}[cloud]
    pipeline_id = f"pipe_{slug}_to_{storage_suffix}"

    all_outputs = _load_bootstrap_outputs()
    cloud_outputs = all_outputs.get(cloud, {})

    # Use description for region keyword inference; fall back to slug
    region = _infer_region(description or intent.pipeline_slug, cloud)
    res = _resource_names(slug, cloud, cloud_outputs)
    defaults = _CLOUD_DEFAULTS[cloud]
    trino_schema = _SCHEMA_MAP.get(domain, slug)
    catalog = defaults["trino_catalog"]

    cloud_setup: dict = {
        "region": region,
        "k8s_namespace": "analytics",
        **res,
        **{k: v for k, v in defaults.items() if k not in ("default_region", "trino_catalog")},
    }

    # Per-cloud bootstrap-output keys copied verbatim into cloud_setup (only when present).
    _BOOTSTRAP_KEYS = {
        "aws":   ("aws_account_id", "state_bucket", "lock_table", "eks_oidc_issuer",
                  "pipeline_irsa_role_name", "pipeline_irsa_role_arn", "oidc_provider_arn"),
        "azure": ("acr_login_server", "aks_cluster_name", "aks_oidc_issuer_url",
                  "state_storage_account", "state_container", "resource_group_name",
                  "pipeline_managed_identity_name", "pipeline_managed_identity_client_id"),
        "gcp":   ("project_id", "region", "artifact_registry_url", "state_bucket",
                  "pipeline_service_account_email", "pipeline_service_account_id"),
    }
    for k in _BOOTSTRAP_KEYS.get(cloud, ()):
        if v := cloud_outputs.get(k):
            cloud_setup[k] = v

    # AWS: a runtime-authored pipeline has no pre-created IRSA role of its own, so point
    # its ServiceAccount at the SHARED pipelines IRSA role (bootstrap, trust = StringLike
    # `system:serviceaccount:analytics:*-insights-sa`). _resource_names() set iam_role_name
    # to a per-slug `<slug>-insights-role` that does NOT exist — override it with the real
    # shared role so cloud_get() can read SSM and the pod can write S3. The SA name stays
    # `<slug>-insights-sa`, which matches the wildcard trust. (No-op for the validated YAML
    # path: that never calls _build_from_answers — it carries its own bootstrap role.)
    if cloud == "aws" and cloud_setup.get("pipeline_irsa_role_name"):
        cloud_setup["iam_role_name"] = cloud_setup["pipeline_irsa_role_name"]

    # Azure: same gap, different mechanism. The managed identity + AKS federated credential
    # are bootstrap-owned; a runtime-authored pipeline has neither. Point it at the SHARED
    # identity (its per-pipeline Terraform binds that identity to its own storage account via
    # azurerm_role_assignment, and outputs its client_id for the SA annotation). Because an
    # Azure federated-credential subject must be EXACT (no wildcard, unlike AWS IRSA), every
    # NL-authored Azure pipeline must use the one FIXED ServiceAccount name the shared
    # credential trusts — override the per-slug `<slug>-insights-sa` with it. (No-op for the
    # validated YAML path: us_crm never calls _build_from_answers.)
    if cloud == "azure" and cloud_setup.get("pipeline_managed_identity_name"):
        cloud_setup["managed_identity_name"] = cloud_setup["pipeline_managed_identity_name"]
        cloud_setup["k8s_service_account_name"] = "pipelines-insights-sa"

    # GCP: same as Azure. The GCP service account + GKE Workload Identity binding are
    # bootstrap-owned; a runtime-authored pipeline has neither. Point it at the SHARED SA (its
    # per-pipeline Terraform binds that SA to its own bucket; project-level objectAdmin already
    # covers it). A GCP WI binding member is EXACT (no wildcard), so every NL-authored GCP
    # pipeline uses the one FIXED KSA the shared binding trusts — override the per-slug SA id,
    # email and KSA. (No-op for the validated YAML path: global_marketing never calls this.)
    if cloud == "gcp" and cloud_setup.get("pipeline_service_account_id"):
        cloud_setup["service_account_id"] = cloud_setup["pipeline_service_account_id"]
        cloud_setup["service_account_email"] = cloud_setup["pipeline_service_account_email"]
        cloud_setup["k8s_service_account_name"] = "pipelines-insights-sa"

    pipeline_conf = {
        "pipeline_id": pipeline_id,
        "owner": intent.owner_team,
        "project_name": f"{slug.replace('_', '-')}-insights",
        "project_folder_name": "multi-cloud-self-healing-agent",
        "source_config": f"configs/databases/{db_type}_{slug}.yaml",
        "business_rules_config": f"configs/business_rules/{slug}_logic.yaml",
        "target_infra_config": f"configs/infra/{_INFRA_CONFIG_NAME[cloud]}.yaml",
        "project_structure": {
            "python_dir": "scripts",
            "sql_dir": "sql",
            "data_dir": "data",
            "requirements_path": "requirements.txt",
            "trino_setup_path": "sql/setup_trino.sql",
            "monitoring_path": "dashboards/monitoring_specs.json",
            "python_script_path": f"scripts/{pipeline_id}.py",
        },
        "shared_services": {
            "trino": {
                "host": "trino.analytics.svc.cluster.local",
                "port": 8080,
                "catalog": catalog,
                "schema": trino_schema,
                "table_name": pipeline_id,
            },
            "grafana": {
                "url": "http://grafana.monitoring.svc.cluster.local",
                "namespace": "monitoring",
            },
        },
        "data_domain": domain,
        "priority": "high",
        "update_frequency": frequency,
        "cloud_provider": cloud,
        f"{cloud}_setup": cloud_setup,
    }

    env_prefix = {"postgres": "POSTGRES_DB", "mysql": "MYSQL_DB", "sqlite": "SQLITE"}[db_type]
    db_conf = {
        "db_type": db_type,
        "default_table": intent.source_table,
        f"env_var_{db_type}_host": f"{env_prefix}_HOST",
        f"env_var_{db_type}_port": f"{env_prefix}_PORT",
        f"env_var_{db_type}_user": f"{env_prefix}_USER",
        f"env_var_{db_type}_password": f"{env_prefix}_PASSWORD",
        f"env_var_{db_type}_name": f"{env_prefix}_NAME",
    }

    quality_standards = [
        {
            "rule_id": r["rule_id"],
            "description": r.get("reason", ""),
            "target_criteria": {
                "column": r["target_column"],
                "condition": r["condition"],
            },
            "on_failure_action": r["action"],
        }
        for r in rules
    ]
    rules_conf = {"quality_standards": quality_standards}
    infra_conf = _INFRA_CONF[cloud].copy()

    dest_uri = _destination_uri(cloud, cloud_setup)

    nl_header = f"**Natural Language Input:** {description}\n\n---\n\n" if description else ""

    task = f"""\
# MISSION OBJECTIVE: {pipeline_id.upper()}

{nl_header}## 🏗️ 1. ARCHITECT SCOPE (DATA LOGIC)

**DATA PIPELINE (PYTHON):**
- Source: `{db_type}` database, table `{db_conf['default_table']}`
- Output format: parquet/snappy
- Destination URI: `{dest_uri}`
- Idempotency: check `{dest_uri}run_date=<today>/` before writing. If data exists, exit 0.
- Save script to: `scripts/{pipeline_id}.py`

**BUSINESS RULES:**
  - See `TRANSFORMATION_LOGIC` in your context — this is the authoritative and complete rules list. Do not infer or skip rules based on this task description.

**CATALOG & OBSERVABILITY:**
- Trino DDL: `sql/setup_trino.sql` — external table at `{dest_uri}` with `run_date` partitioning
- Trino target: `{catalog}.{trino_schema}.{pipeline_id}`
- Grafana: `dashboards/monitoring_specs.json` with 60-minute Data Silence alert

---

## 🛠️ 2. INFRA SCOPE (DEPLOYMENT & AUTOMATION)

**TERRAFORM:** Deploy {cloud.upper()} storage and identity/IAM resources.
**K8S:** Deploy namespaces, Trino, Grafana, Prometheus + Pipeline Job.
**CI/CD:** `/.github/workflows/{pipeline_id}_pipeline.yml`

---

## 🔒 3. GLOBAL CONSTRAINTS

- All DB credentials via `cloud_get()` — never `os.getenv()` for host/user/password/db. GitHub Secrets are for CI/CD auth only (ECR, cloud CLI).
- Every agent MUST query the Vector Store for domain standards before writing.
- Final signal: `echo "Deployment Complete"`.
"""

    _save_generated_configs(pipeline_id, pipeline_conf, db_conf, rules_conf, infra_conf, task)

    return pipeline_conf, db_conf, rules_conf, infra_conf, pipeline_id, task


