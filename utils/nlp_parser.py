def _slugify(text: str) -> str:
    text = text.lower().strip()
    text = re.sub(r"[^a-z0-9\s_-]", "", text)
    text = re.sub(r"[\s-]+", "_", text)
    return text[:30].strip("_")


def _infer_region(description: str, cloud: str) -> str:
    desc = description.lower()
    for keyword, region in _REGION_MAP.items():
        if keyword in desc:
            return region
    return _CLOUD_DEFAULTS[cloud]["default_region"]


def _destination_uri(cloud: str, cloud_setup: dict) -> str:
    if cloud == "aws":
        return f"s3://{cloud_setup['bucket_name']}/processed/"
    elif cloud == "gcp":
        return f"gs://{cloud_setup['bucket_name']}/processed/"
    else:
        c = cloud_setup["container_name"]
        a = cloud_setup["storage_account_name"]
        return f"abfss://{c}@{a}.dfs.core.windows.net/processed/"


def _resource_names(slug: str, cloud: str, cloud_outputs: dict) -> dict:
    """
    Generate cloud resource names from the pipeline slug.
    Uses bootstrap outputs where available for values that require
    infrastructure knowledge (account IDs, project IDs, etc.).
    """
    dash = slug.replace("_", "-")
    if cloud == "aws":
        return {
            "bucket_name": f"{dash}-insights-data",
            "ecr_repository_name": f"{dash}-pipeline-repo",
            "iam_role_name": f"{dash}-insights-role",
            "k8s_service_account_name": f"{dash}-insights-sa",
            "state_key": f"terraform/{dash}-insights/terraform.tfstate",
        }
    elif cloud == "azure":
        acct = re.sub(r"[^a-z0-9]", "", slug)[:20] + "storage"
        acct = acct[:24]
        return {
            "storage_account_name": acct,
            "container_name": f"{dash}-insights-data",
            "managed_identity_name": f"{dash}-insights-identity",
            "k8s_service_account_name": f"{dash}-insights-sa",
            "state_key": f"azure/{dash}-insights/terraform.tfstate",
        }
    else:  # gcp
        sa_id = f"{dash[:20]}-sa"
        project_id = cloud_outputs.get("project_id")
        sa_email = (
            f"{sa_id}@{project_id}.iam.gserviceaccount.com"
            if project_id
            else f"{sa_id}@<GCP_PROJECT_ID>.iam.gserviceaccount.com"
        )
        return {
            "bucket_name": f"{dash}-insights-data",
            "service_account_id": sa_id,
            "service_account_email": sa_email,
            "k8s_service_account_name": f"{dash}-insights-sa",
            "state_prefix": f"gcp/{dash}-insights/terraform.tfstate",
        }

