def _save_generated_configs(
    pipeline_id: str,
    pipe_conf: dict,
    db_conf: dict,
    rules_conf: dict,
    infra_conf: dict,
    task: str,
) -> None:
    """
    Persist generated configs to disk so the pipeline can be rerun via YAML mode.

    Writes four files (infra configs are static and never overwritten):
      1. {CONFIGS_DIR}/pipelines/{pipeline_name}_pipeline.yaml  — full pipeline config
      2. {CONFIGS_DIR}/pipelines/{pipeline_name}_objective.md   — mission objective (task)
      3. {CONFIGS_DIR}/databases/{db_type}_{pipeline_name}.yaml — database connection config
      4. {CONFIGS_DIR}/business_rules/{pipeline_name}_logic.yaml — quality rules

    Saving is best-effort: any I/O error is logged as a warning and never re-raised.

    Args:
        pipeline_id: Full pipeline identifier, e.g. ``pipe_eu_sales_to_s3``.
        pipe_conf:   Pipeline configuration dict (mirrors hand-written pipeline YAMLs).
        db_conf:     Database connection dict built by ``build_pipeline_bundle_from_nl``.
        rules_conf:  Quality-standards dict, e.g. ``{"quality_standards": [...]}``.
        infra_conf:  Cloud infrastructure dict (not saved — static files already exist).
        task:        Formatted mission-objective markdown string.
    """
    try:
        # Derive a clean pipeline name: pipe_eu_sales_to_s3 → eu_sales
        pipeline_name = re.sub(r"^pipe_", "", pipeline_id)
        pipeline_name = re.sub(r"_to_(s3|azure|gcp)$", "", pipeline_name)

        db_type = db_conf.get("db_type", "postgres")

        pipelines_dir = os.path.join(CONFIGS_DIR, "pipelines")
        databases_dir = os.path.join(CONFIGS_DIR, "databases")
        rules_dir = os.path.join(CONFIGS_DIR, "business_rules")

        for d in (pipelines_dir, databases_dir, rules_dir):
            os.makedirs(d, exist_ok=True)

        # ── 1. Pipeline YAML ─────────────────────────────────────────────
        pipeline_yaml_path = os.path.join(
            pipelines_dir, f"{pipeline_name}_pipeline.yaml"
        )
        with open(pipeline_yaml_path, "w", encoding="utf-8") as fh:
            yaml.dump(pipe_conf, fh, default_flow_style=False, allow_unicode=True)

        # ── 2. Objective markdown ─────────────────────────────────────────
        objective_path = os.path.join(
            pipelines_dir, f"{pipeline_name}_objective.md"
        )
        with open(objective_path, "w", encoding="utf-8") as fh:
            fh.write(task)

        # ── 3. Database YAML — normalise keys to match hand-written files ─
        # Generated keys look like env_var_postgres_host; existing files use env_var_host.
        db_yaml: dict = {
            "db_id": f"{db_type}_{pipeline_name}",
            "db_type": db_type,
            "connection_type": "network",
        }
        for k, v in db_conf.items():
            if k.startswith("env_var_"):
                norm_key = re.sub(rf"^env_var_{re.escape(db_type)}_", "env_var_", k)
                db_yaml[norm_key] = v
        db_yaml["default_table"] = db_conf.get("default_table", "")
        db_yaml["description"] = (
            f"Auto-generated database config for {pipeline_name}."
        )
        db_yaml_path = os.path.join(
            databases_dir, f"{db_type}_{pipeline_name}.yaml"
        )
        with open(db_yaml_path, "w", encoding="utf-8") as fh:
            yaml.dump(db_yaml, fh, default_flow_style=False, allow_unicode=True)

        # ── 4. Business-rules YAML ────────────────────────────────────────
        rules_yaml_path = os.path.join(
            rules_dir, f"{pipeline_name}_logic.yaml"
        )
        with open(rules_yaml_path, "w", encoding="utf-8") as fh:
            yaml.dump(rules_conf, fh, default_flow_style=False, allow_unicode=True)

        print(
            f"\n  ✅ Configs saved — rerun anytime with:\n"
            f"     python main.py {pipeline_name}"
        )

    except Exception as exc:  # best-effort: never crash the pipeline run
        print(f"  ⚠️  Config save failed (non-fatal): {exc}")


